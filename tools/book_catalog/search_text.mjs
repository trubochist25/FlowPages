function clean(value) {
  return String(value ?? '').replace(/<[^>]*>/g, ' ').replace(/\s+/g, ' ').trim();
}

function unique(values) {
  const seen = new Set();
  return values.filter((value) => {
    const key = clean(value).toLocaleLowerCase('ru').replace(/ё/g, 'е');
    if (!key || seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

function sourceSubjects(work) {
  return unique((work?.subject ?? []).map(clean))
    .filter((value) => value.length >= 4 && value.length <= 70)
    .filter((value) => !genericSubject.test(value))
    .filter((value) => !/^(general|miscellaneous|juvenile fiction)$/i.test(value))
    .slice(0, 10);
}

function translatedSubjectDetails(work) {
  const haystack = (work?.subject ?? []).map(clean).join(' | ');
  return unique(
    subjectTranslations
      .filter(([pattern]) => pattern.test(haystack))
      .map(([, translation]) => translation)
  ).slice(0, 8);
}

function vocabularyTerms(values, vocabulary, limitPerValue) {
  return unique(values.flatMap((value) => [
    value,
    ...String(vocabulary[value] ?? '')
      .split(',')
      .map(clean)
      .filter(Boolean)
      .slice(0, limitPerValue)
  ]));
}

function volumeProfile(pages) {
  if (pages <= 160) return 'очень короткая и небольшая книга; быстрое чтение, которое можно закончить за один вечер';
  if (pages <= 250) return 'короткая и компактная книга; подходит для быстрого чтения или нескольких вечеров';
  if (pages <= 450) return 'книга среднего объёма; не слишком короткое и не слишком долгое чтение';
  if (pages <= 650) return 'объёмная и длинная книга для неспешного погружения';
  return 'очень объёмная книга; долгое чтение и глубокое погружение в материал';
}

function eraProfile(year) {
  if (year < 1900) return 'произведение XIX века или более ранней эпохи, старая литература и исторический контекст';
  if (year < 1970) return 'литература первой половины XX века или послевоенного периода';
  if (year < 2010) return 'литература конца XX или начала XXI века';
  return 'современная книга XXI века, актуальное чтение';
}

function paceProfile(pace) {
  if (pace === 'быстрый') return 'быстрый темп, активное развитие событий, читается легко и увлекательно';
  if (pace === 'медленный') return 'медленный и неспешный темп, внимание к деталям, вдумчивое чтение';
  return 'средний и ровный темп, баланс событий и размышлений';
}

function audienceProfile(book, isNonfiction) {
  if (isNonfiction) {
    return `Подойдёт читателю, который ищет полезную, объясняющую или развивающую литературу по направлениям: ${book.genres.join(', ')}.`;
  }
  const moods = book.mood.join(', ');
  return `Подойдёт читателю, который ищет художественную историю в жанрах ${book.genres.join(', ')} с настроением: ${moods}.`;
}

export function buildSearchText(book, work = {}) {
  const isNonfiction = book.genres.some((genre) => nonfictionGenres.has(genre));
  const genres = vocabularyTerms(book.genres, genreVocabulary, 4);
  const themes = vocabularyTerms(book.themes, themeVocabulary, 3);
  const moods = vocabularyTerms(book.mood, moodVocabulary, 3);
  const subjects = sourceSubjects(work);
  const translatedDetails = translatedSubjectDetails(work);
  const originalTitle = clean(book.sourceTitle);
  const identity = [
    `Книга «${book.title}».`,
    `Автор: ${book.author}.`,
    originalTitle && originalTitle.toLocaleLowerCase() !== book.title.toLocaleLowerCase()
      ? `Оригинальное название: ${originalTitle}.`
      : '',
    book.series ? `Цикл или серия: ${book.series}.` : ''
  ].filter(Boolean).join(' ');

  return [
    identity,
    `Жанры и близкие понятия: ${genres.join(', ')}.`,
    `Темы и мотивы: ${themes.join(', ')}.`,
    translatedDetails.length ? `Фактические сюжетные и предметные детали: ${translatedDetails.join('; ')}.` : '',
    subjects.length ? `Фактические предметные рубрики источника: ${subjects.join('; ')}.` : '',
    `Атмосфера: ${moods.join(', ')}. Темп: ${paceProfile(book.pace)}.`,
    `Объём: ${book.pages} страниц; ${volumeProfile(book.pages)}. Год: ${book.year}; ${eraProfile(book.year)}. Возраст: ${book.ageRating}.`,
    audienceProfile(book, isNonfiction)
  ].filter(Boolean).join(' ');
}
